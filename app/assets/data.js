/* ============ مولِّدٌ ببذرةٍ ثابتة ============ */
function mulberry32(a) {
  return function () {
    a |= 0; a = a + 0x6D2B79F5 | 0;
    let t = Math.imul(a ^ a >>> 15, 1 | a);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}
function seedOf(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}

/* توليد ثلاث دوراتٍ متتالية لمؤشّرٍ في جهة */
function series(entId, catKey, kpi) {
  const rnd = mulberry32(seedOf(entId + catKey + kpi.id));
  const tgt = kpi.target;
  const down = kpi.better === 'down';
  const band = kpi.better === 'band';

  // موقعٌ مبدئيّ نسبةً إلى المستهدَف: أغلبيّةٌ قريبةٌ منه، وذيلٌ متعثّر
  const bias = (rnd() - 0.40) * 0.50;
  // ميلٌ لكل دورة: أغلب الجهات تتحسّن، وبعضها يتراجع
  const slope = (rnd() * 0.92 - 0.20) * 0.085;

  const out = [];
  for (let c = 0; c < 3; c++) {
    const noise = (rnd() - 0.5) * 0.018;
    let rel = bias + slope * c + noise;              // انحرافٌ نسبيّ عن المستهدَف
    let v = band ? 77 + rel * 26 : tgt * (1 + (down ? -rel : rel));
    v = Math.max(0, v);
    // سقفٌ مقارِبٌ للنِّسَب: لا تتجاوز ١٠٠٪ ولا تبلغها، ويبقى الترتيب محفوظاً.
    // وأثرُه مقصود: مَن قارب السقف يضيق مجالُ تحسُّنه — وهو «أثرُ السقف» الذي
    // يُعاقِب المتفوّقَ الثابت في شرط «الاتجاه الموجب لثلاث دورات». انظر README.
    if (kpi.unit === '٪' && v > 99) v = 99 + 0.8 * (v - 99) / (1 + (v - 99));
    out.push(+v.toFixed(kpi.unit === 'يوم' ? 2 : 1));
  }
  return out;
}

/* ============ بناء المشاركات ============
   المشاركةُ ملفٌّ مستقلّ لكلّ (جهة × فئة) — لا لكلّ (جهة × مسار).
   هذا ما تفرضه النتيجةُ المعلنة: مسارُ إنقاذ الأرواح توّج خمسَ جهاتٍ
   موزَّعةً على ثلاث فئات، ولو كانت التصفيةُ على مستوى المسار لتوّج ثلاثاً. */

/** هل تُقبَل هذه الجهةُ في هذه الفئة؟ وحدةُ التنافس تحكم. */
function fits(ent, cat) {
  if (ent.kind === 'authority') return false;      // الجهةُ الأمّ تُمنَح وساماً ولا تدخل مساراً
  return cat.unit === 'any' || cat.unit === ent.kind;
}

const CASES = (() => {
  const out = [];
  ENTITIES.forEach(ent => {
    const rnd = mulberry32(seedOf(ent.id + 'cats'));
    const pool = CATS.filter(c => fits(ent, c));
    if (!pool.length) return;
    const n = Math.min(pool.length, ent.kind === 'cluster' ? 2 + Math.floor(rnd() * 2) : 3 + Math.floor(rnd() * 3));
    const picked = pool.slice().sort(() => rnd() - 0.5).slice(0, n);
    picked.forEach(cat => {
      const kpis = kpisOf(cat.key);
      const vals = {};
      kpis.forEach(k => { vals[k.id] = series(ent.id, cat.key, k); });

      // تغطية المصدر الرسميّ: ناقصةٌ حيث الربطُ جزئيّ
      const r2 = mulberry32(seedOf(ent.id + cat.key + 'feed'));
      const missing = [];
      if (ent.feed === 'partial') {
        cat.kpis.forEach(k => { if (r2() < 0.28) missing.push(k.id); });
        if (r2() < 0.45) missing.push('ESAT');
      }
      out.push({
        id: `${ent.id}-${cat.key.replace(':', '-')}`,
        entity: ent.id, track: cat.track, cat: cat.id, key: cat.key,
        vals, missing,
        registeredAt: '2026-02-' + String(3 + Math.floor(mulberry32(seedOf(ent.id + cat.key))() * 22)).padStart(2, '0')
      });
    });
  });
  return out;
})();

